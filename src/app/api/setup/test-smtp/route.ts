import { NextRequest, NextResponse } from "next/server";
import { isSystemInstalled } from "@/features/setup/setup.service";
import { createTransporter, SmtpConfig } from "@/lib/email/mailer";
import { withErrorHandling } from "@/lib/api-handler";
import { AppError } from "@/lib/errors";

export async function POST(req: NextRequest) {
  return withErrorHandling(req, async () => {
    const installed = await isSystemInstalled();
    if (installed) {
      throw new AppError("System is already configured and locked.", 403);
    }

    const body = await req.json();
    const host = body.host?.trim();
    const port = parseInt(body.port, 10) || 587;
    const encryption = body.encryption || "tls";
    const user = body.user?.trim();
    const pass = body.pass?.trim();
    const fromAddress = body.fromAddress?.trim() || "noreply@hospital.local";
    const fromName = body.fromName?.trim() || "Clinical Prescriptions";
    const testRecipient = body.testRecipient?.trim();

    if (!host) {
      throw new AppError("SMTP host is required.", 400);
    }
    if (!testRecipient || !testRecipient.includes("@")) {
      throw new AppError("A valid test recipient email address is required.", 400);
    }

    const secure = encryption === "ssl" || port === 465;
    const config: SmtpConfig = {
      host,
      port,
      secure,
      auth: user && pass ? { user, pass } : undefined,
      fromAddress,
      fromName,
      encryption,
      enabled: true,
    };

    const transporter = createTransporter(config);

    // Verify SMTP connection
    await transporter.verify();

    // Send test email
    const info = await transporter.sendMail({
      from: `"${fromName}" <${fromAddress}>`,
      to: testRecipient,
      subject: `[${fromName}] SMTP Connection Test Successful`,
      html: `
        <div style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; max-width: 580px; margin: 0 auto; padding: 28px; border: 1px solid #e2e8f0; border-radius: 16px; background: #ffffff;">
          <div style="display: flex; align-items: center; margin-bottom: 20px;">
            <div style="background: #0f766e; color: #ffffff; padding: 8px 14px; border-radius: 8px; font-weight: bold; font-size: 14px;">
              ${fromName}
            </div>
          </div>
          <h2 style="color: #0f172a; margin-top: 0; font-size: 20px;">SMTP Connection Verified!</h2>
          <p style="color: #475569; font-size: 14px; line-height: 1.6;">
            Congratulations! Your outgoing mail server configuration has been successfully tested and is ready to deliver prescriptions, account recovery links, and patient notifications.
          </p>
          <div style="background: #f8fafc; border: 1px solid #e2e8f0; padding: 14px 18px; border-radius: 12px; margin: 20px 0; font-size: 13px; color: #334155;">
            <div><strong>Host:</strong> ${host}:${port}</div>
            <div><strong>Encryption:</strong> ${encryption.toUpperCase()}</div>
            <div><strong>Sender:</strong> &lt;${fromAddress}&gt;</div>
            <div><strong>Recipient:</strong> &lt;${testRecipient}&gt;</div>
          </div>
          <p style="color: #94a3b8; font-size: 12px; margin-top: 24px; border-top: 1px solid #f1f5f9; padding-top: 16px;">
            This diagnostic message was generated by the System Setup Wizard.
          </p>
        </div>
      `,
      text: `[${fromName}] SMTP Connection Verified!\n\nYour outgoing mail server (${host}:${port}) has been tested and is ready to deliver messages to ${testRecipient}.`,
    });

    return NextResponse.json({
      success: true,
      message: `Test email successfully delivered to ${testRecipient}!`,
      messageId: info.messageId,
    });
  });
}
